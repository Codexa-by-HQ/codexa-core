function renderFixedHeaders(headers: readonly FixedHeader[]): string {
	if (headers.length === 0) return '[]';
	return `[${
		headers.map((header) =>
			`[${JSON.stringify(header.name)}, ${JSON.stringify(header.value)}]`
		).join(', ')
	}]`;
}

function renderDeclarationNamespace(
	namespace: string,
	routes: readonly RouteModel[],
	options: { readonly static: boolean },
): string {
	return `\t${options.static ? 'static ' : ''}${namespace}: ${
		renderNamespaceType(routes)
	};`;
}

function renderDeclarationMethod(route: RouteModel): string {
	return `\t\treadonly ${route.methodName}: CodexaSdkMethod<${route.typePrefix}Input, ${route.typePrefix}Response>;`;
}

function firstRequestBodySchema(
	operation: OpenApiOperation,
): JsonSchemaObject | undefined {
	const content = operation.requestBody?.content;
	if (content === undefined) return undefined;
	return content['application/json']?.schema ??
		Object.values(content).at(0)?.schema;
}

function firstSuccessResponseSchema(
	operation: OpenApiOperation,
): JsonSchemaObject | undefined {
	const responses = Object.entries(operation.responses).sort((
		[left],
		[right],
	) => left.localeCompare(right));
	const success = responses.find(([status]) => status.startsWith('2')) ??
		responses[0];
	if (success === undefined || success[1].content === undefined) {
		return undefined;
	}
	return success[1].content['application/json']?.schema ??
		Object.values(success[1].content).at(0)?.schema;
}

function parametersToType(parameters: readonly OpenApiParameter[]): string {
	if (parameters.length === 0) return 'Record<string, never>';
	const fields = parameters.map((parameter) =>
		`\treadonly ${JSON.stringify(parameter.name)}${
			parameter.required ? '' : '?'
		}: ${schemaToType(parameter.schema)};`
	);
	return `{\n${fields.join('\n')}\n}`;
}

function schemaToType(schema: JsonSchemaObject | undefined): string {
	if (schema === undefined) return 'unknown';
	const rendered = renderSchemaType(schema);
	const nullable = schema.nullable === true ||
		(Array.isArray(schema.type) && schema.type.includes('null'));
	return nullable && rendered !== 'null' ? `${rendered} | null` : rendered;
}

function renderSchemaType(schema: JsonSchemaObject): string {
	if (schema.const !== undefined) return JSON.stringify(schema.const);
	if (Array.isArray(schema.enum)) {
		return schema.enum.map((value) => JSON.stringify(value)).join(' | ') ||
			'unknown';
	}
	if (Array.isArray(schema.anyOf)) {
		return schema.anyOf.map((item) => schemaToType(item)).join(' | ');
	}
	if (Array.isArray(schema.oneOf)) {
		return schema.oneOf.map((item) => schemaToType(item)).join(' | ');
	}
	if (Array.isArray(schema.allOf)) {
		return schema.allOf.map((item) => schemaToType(item)).join(' & ');
	}

	const schemaTypes = Array.isArray(schema.type)
		? schema.type.filter((type) => type !== 'null')
		: schema.type === undefined
		? []
		: [schema.type];
	if (schemaTypes.length > 1) {
		return schemaTypes.map((type) =>
			renderSchemaType({ ...schema, type, nullable: false })
		).join(' | ');
	}

	const schemaType = schemaTypes[0];
	if (schemaType === 'null') return 'null';
	if (schemaType === 'string') return 'string';
	if (schemaType === 'number' || schemaType === 'integer') return 'number';
	if (schemaType === 'boolean') return 'boolean';
	if (schemaType === 'array') {
		return `readonly (${schemaToType(schema.items)})[]`;
	}
	if (schemaType === 'object' || schema.properties !== undefined) {
		return objectSchemaToType(schema);
	}
	return 'unknown';
}

function objectSchemaToType(schema: JsonSchemaObject): string {
	const properties = schema.properties ?? {};
	const required = new Set(schema.required ?? []);
	const fields = Object.entries(properties).map(([key, value]) =>
		`\treadonly ${JSON.stringify(key)}${required.has(key) ? '' : '?'}: ${
			schemaToType(value)
		};`
	);
	if (isRecord(schema.additionalProperties)) {
		fields.push(
			fields.length === 0
				? `\treadonly [key: string]: ${
					schemaToType(schema.additionalProperties)
				};`
				: '\treadonly [key: string]: unknown;',
		);
	} else if (schema.additionalProperties === true) {
		fields.push('\treadonly [key: string]: unknown;');
	}
	return fields.length === 0
		? 'Record<string, unknown>'
		: `{\n${fields.join('\n')}\n}`;
}
