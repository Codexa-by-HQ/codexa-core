function renderStaticMethod(clientName: string, route: RouteModel): string {
	return `\t\t${route.methodName}: Object.assign(
\t\t\t(input: ${route.typePrefix}Input = {}) => {
\t\t\t\t${clientName}.checkPermission(${JSON.stringify(route.permission)});
\t\t\t\treturn ${clientName}.request<${route.typePrefix}Response>(
\t\t\t\t\t${JSON.stringify(route.method)},
\t\t\t\t\t${JSON.stringify(route.path)},
\t\t\t\t\tmergeRouteInput(input, ${renderFixedHeaders(route.fixedHeaders)}),
\t\t\t\t);
\t\t\t},
\t\t\t{ __permission: ${JSON.stringify(route.permission)} },
\t\t) as CodexaSdkMethod<${route.typePrefix}Input, ${route.typePrefix}Response>,`;
}

