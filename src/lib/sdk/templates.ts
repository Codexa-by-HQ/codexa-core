import { isRecord, toIdentifier, toPascalIdentifier } from './helpers.ts';

interface RouteModel {
	readonly namespace: string;
	readonly methodName: string;
	readonly method: string;
	readonly path: string;
	readonly permission: string;
	readonly operation: OpenApiOperation;
	readonly typePrefix: string;
	readonly fixedHeaders: readonly FixedHeader[];
}

interface FixedHeader {
	readonly name: string;
	readonly value: string;
}

export function collectRoutes(document: OpenApiDocument): RouteModel[] {
	const routes: RouteModel[] = [];
	for (const [path, methods] of Object.entries(document.paths)) {
		for (const [rawMethod, operation] of Object.entries(methods)) {
			const permission = resolvePermission(operation, rawMethod, path);
			const namespace = resolveNamespace(operation, permission);
			const methodName = toIdentifier(
				resolveMethodName(permission, namespace),
			);
			routes.push({
				namespace,
				methodName,
				method: rawMethod.toUpperCase(),
				path: resolveClientPath(operation, path),
				permission,
				operation,
				typePrefix: toPascalIdentifier(`${namespace}.${methodName}`),
				fixedHeaders: collectFixedHeaders(operation),
			});
		}
	}
	return dedupeRouteMethodNames(routes).sort((left, right) =>
		`${left.namespace}.${left.methodName}`.localeCompare(
			`${right.namespace}.${right.methodName}`,
		)
	);
}

function resolvePermission(
	operation: OpenApiOperation,
	method: string,
	path: string,
): string {
	const routeName = operation['x-codexa-route-name'];
	if (typeof routeName === 'string' && routeName.trim() !== '') {
		return routeName;
	}
	if (
		typeof operation.operationId === 'string' &&
		operation.operationId !== ''
	) {
		return operation.operationId;
	}
	return `${method.toLowerCase()}${path.replace(/[^a-zA-Z0-9]+/g, '.')}`;
}

function resolveNamespace(
	operation: OpenApiOperation,
	permission: string,
): string {
	const pluginName = operation['x-codexa-plugin'];
	if (typeof pluginName === 'string' && pluginName.trim() !== '') {
		return toIdentifier(pluginName);
	}
	const firstTag = operation.tags?.find((tag) => tag.trim() !== '');
	if (firstTag !== undefined) return toIdentifier(firstTag);
	return toIdentifier(permission.split('.')[0] ?? 'api');
}

function resolveClientPath(
	operation: OpenApiOperation,
	openApiPath: string,
): string {
	const originalPath = operation['x-codexa-original-path'];
	if (typeof originalPath === 'string' && originalPath.trim() !== '') {
		return originalPath;
	}
	return openApiPath.replace(/\{([^}]+)\}/g, ':$1');
}

function resolveMethodName(permission: string, namespace: string): string {
	const parts = permission.split('.').filter(Boolean);
	if (parts[0] === namespace && parts.length > 1) {
		return parts.slice(1).join('.');
	}
	return parts.length > 1 ? parts.slice(1).join('.') : permission;
}

function collectFixedHeaders(operation: OpenApiOperation): FixedHeader[] {
	const version = operation['x-codexa-version'];
	if (version === undefined) return [];
	return [{
		name: operation['x-codexa-version-header'] ?? 'X-Version',
		value: version,
	}];
}

function dedupeRouteMethodNames(routes: readonly RouteModel[]): RouteModel[] {
	const groups = new Map<string, RouteModel[]>();
	for (const route of routes) {
		const key = `${route.namespace}.${route.methodName}`;
		const group = groups.get(key) ?? [];
		group.push(route);
		groups.set(key, group);
	}

	const used = new Set<string>();
	return routes.map((route) => {
		const key = `${route.namespace}.${route.methodName}`;
		const group = groups.get(key) ?? [];
		if (group.length === 1 && !used.has(key)) {
			used.add(key);
			return route;
		}

		const methodName = uniqueMethodName(route, used);
		used.add(`${route.namespace}.${methodName}`);
		return {
			...route,
			methodName,
			typePrefix: toPascalIdentifier(`${route.namespace}.${methodName}`),
		};
	});
}

function uniqueMethodName(route: RouteModel, used: Set<string>): string {
	const candidates = [
		route.operation['x-codexa-version'] === undefined
			? undefined
			: `${route.methodName}.v.${route.operation['x-codexa-version']}`,
		route.operation.operationId,
		`${route.methodName}.${route.method}.${route.path}`,
	];
	for (const candidate of candidates) {
		if (candidate === undefined || candidate === '') continue;
		const methodName = toIdentifier(candidate);
		if (!used.has(`${route.namespace}.${methodName}`)) return methodName;
	}

	let index = 2;
	while (used.has(`${route.namespace}.${route.methodName}${index}`)) index++;
	return `${route.methodName}${index}`;
}

